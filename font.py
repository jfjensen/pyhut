GLYPH_WIDTH = 5
GLYPH_HEIGHT = 7


def _pack(rows: List[str]) -> List[int]:
    cols = []
    for x in range(GLYPH_WIDTH):
        byte = 0
        for y in range(GLYPH_HEIGHT):
            if x < len(rows[y]) and rows[y][x] != " ":
                byte |= 1 << y
        cols.append(byte)
    return cols


FONT: Dict[str, List[int]] = {ch: _pack(rows) for ch, rows in _GLYPHS_SRC.items()}


def glyph(ch: str) -> List[int]:
    """Return 5 column-bytes for a character; uppercase fallback, space if unknown."""
    if ch in FONT:
        return FONT[ch]
    up = ch.upper()
    if up in FONT:
        return FONT[up]
    return FONT[" "]
